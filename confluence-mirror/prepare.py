def h1(text, fallback):
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback

def rewrite_links(text, repo, relpath):
    base_dir = os.path.dirname(relpath).replace("\\", "/")
    def sub(m):
        label, target = m.group(1), m.group(2).strip()
        if target.startswith(("http://", "https://", "mailto:", "#")):
            return m.group(0)
        path = target.split("#")[0]
        if not path:
            return m.group(0)
        # resolve relative to the file's directory inside the repo
        parts = []
        for seg in ((base_dir + "/" + path) if base_dir else path).split("/"):
            if seg in ("", "."):
                continue
            if seg == "..":
                if parts:
                    parts.pop()
                continue
            parts.append(seg)
        rel = "/".join(parts)
        return f"[{label}]({GH}/{repo}/blob/main/{rel})"
    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", sub, text)

def load(repo, relpath):
    p = os.path.join(REPOS[repo], relpath.replace("/", os.sep))
    with open(p, encoding="utf-8-sig") as f:
        return f.read()

manifest = []

def add_page(key, title, parent, body, source_desc):
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
    footer = (f"\n\n---\n\n*Mirror of `{source_desc}` in the ai-workspace-kit repositories. "
              f"Git is the source of truth; this page is regenerated by the Confluence mirror sync "
              f"(content hash `{digest}`).*\n")
    full = body.rstrip() + footer
    fn = key + ".md"
    with open(os.path.join(OUT, fn), "w", encoding="utf-8", newline="\n") as f:
        f.write(full)
    manifest.append({"key": key, "title": title, "parent": parent,
                     "payload": fn, "source": source_desc, "sha256": digest})
    return digest

